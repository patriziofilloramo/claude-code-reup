import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'

const rootPackagePath = 'package.json'
const rootLockPath = 'package-lock.json'
const extensionPackagePath = 'extension/package.json'
const extensionLockPath = 'extension/package-lock.json'
const generatedVersionPath = 'src/config/version.ts'

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function writeJson(path, value) {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`)
}

function assertSemver(version) {
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`Root package version is not valid SemVer: ${version}`)
  }
}

function syncLockfileVersion(lockfile, version) {
  lockfile.version = version
  if (lockfile.packages?.['']) lockfile.packages[''].version = version
}

const rootPackage = readJson(rootPackagePath)
const version = rootPackage.version
assertSemver(version)

const rootLock = readJson(rootLockPath)
syncLockfileVersion(rootLock, version)
writeJson(rootLockPath, rootLock)

const extensionPackage = readJson(extensionPackagePath)
extensionPackage.version = version
writeJson(extensionPackagePath, extensionPackage)

const extensionLock = readJson(extensionLockPath)
syncLockfileVersion(extensionLock, version)
writeJson(extensionLockPath, extensionLock)

writeFileSync(
  generatedVersionPath,
  `// Generated by scripts/sync-version.mjs. Do not edit by hand.\nexport const APP_VERSION = '${version}'\n`
)

process.stdout.write(`Synced Reup version ${version}\n`)
