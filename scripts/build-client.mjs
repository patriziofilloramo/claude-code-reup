/**
 * Builds src/web/client.js from the segment files in src/web/client/.
 *
 * The browser application is deliberately kept as a single file (no runtime
 * module system, no bundler dependency). This script concatenates the logical
 * segments — each owning a cohesive concern — into one IIFE-wrapped output.
 *
 * Source segments are in src/web/client/ and named 00-*.js … 16-*.js to make
 * their load order unambiguous. All segments share the enclosing IIFE scope, so
 * variables declared in one segment are visible to segments that follow — the
 * same semantics as the original monolithic file.
 *
 * Usage:
 *   node scripts/build-client.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const SEGMENTS = [
  '00-strings.js', // user-facing strings and lightweight formatter helpers
  '01-config.js', // tunable constants, risk rank
  '02-state.js', // mutable application state (all let variables)
  '03-elements.js', // DOM element references
  '04-format-request.js', // formatters (relativeTime, escapeHtml…) + HTTP helpers
  '05-projects.js', // project list rendering and selection
  '06-sessions.js', // session view model, filtering, and selection
  '07-filter-inspector.js', // filter pills, sort control, session inspector
  '08-session-list.js', // session rows, bulk actions, rename flow
  '09-resume.js', // resume confirmation dialog and terminal launch
  '10-instructions-drawer.js', // CLAUDE.md editor drawer
  '11-diagnostics-drawer.js', // Lost & Found diagnostics drawer
  '12-new-session.js', // start-new-session action
  '13-ctx-menu.js', // context menu (project and session)
  '14-search.js', // search bar, deep-search mode, keyboard shortcuts
  '15-data.js', // data refresh, SSE live updates, bootstrap
  '16-theme.js', // theme cycling, persistence, Matrix rain easter egg
]

const ROOT = process.cwd()
const CLIENT_DIR = join(ROOT, 'src', 'web', 'client')
const OUT_PATH = join(ROOT, 'src', 'web', 'client.js')

const HEADER = `/**
 * Standalone browser application — generated by scripts/build-client.mjs.
 * Edit the source segments in src/web/client/ instead of this file.
 *
 * This remains one script deliberately: splitting it without a browser build
 * step would require shared globals and make ownership less clear. Strong
 * sections and responsibility-oriented names keep the file navigable instead.
 */
;(function () {`

const FOOTER = `})()\n`

const contents = await Promise.all(SEGMENTS.map((name) => readFile(join(CLIENT_DIR, name), 'utf8')))

const output = HEADER + '\n' + contents.join('') + FOOTER
await writeFile(OUT_PATH, output)

const lineCount = output.split('\n').length
console.log(`client.js rebuilt — ${SEGMENTS.length} segments, ${lineCount} lines`)
